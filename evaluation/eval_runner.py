"""Benchmark runner for the hybrid retrieval engine.

Usage::

    python -m evaluation.eval_runner                       # print summary
    python -m evaluation.eval_runner --report evaluation/benchmark_report.md
    python -m evaluation.eval_runner --min-recall 0.9 --min-rejection 1.0   # CI gate

Metric definitions (computed over answerable cases, categories A and B):

* **Precision@5** — relevant cards among the returned cards ÷ number returned
  (the engine prunes low-scoring chunks, so it may return fewer than 5).
* **Recall@5** — relevant cards in the Top-5 ÷ all relevant cards.
* **MRR** — mean of 1 / rank of the first relevant card (0 if none).
* **False refusal rate** — answerable cases the guardrail wrongly declined.

Over category C (out-of-domain) cases:

* **Hallucination rejection rate** — cases the guardrail correctly declined.

Latency is wall-clock time of ``engine.search`` per query (index build excluded).
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from dataclasses import asdict, dataclass
from pathlib import Path

from src.chunker import load_cards
from src.hybrid_search import HybridSearchEngine

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DATASET = ROOT / "evaluation" / "benchmark_dataset.json"
DEFAULT_KB = ROOT / "knowledge-base" / "minh-primary-evidence.md"
K = 5


@dataclass
class CaseResult:
    id: str
    category: str
    query: str
    retrieved: list[str]
    relevant: list[str]
    expect_refusal: bool
    refused: bool
    precision: float | None
    recall: float | None
    reciprocal_rank: float | None
    latency_ms: float
    passed: bool


def evaluate_case(engine: HybridSearchEngine, case: dict) -> CaseResult:
    t0 = time.perf_counter()
    res = engine.search(case["query"])
    latency = (time.perf_counter() - t0) * 1000
    retrieved = res.card_ids[:K]
    relevant = case["relevant_cards"]

    precision = recall = rr = None
    if not case["expect_refusal"]:
        hits = [c for c in retrieved if c in relevant]
        precision = len(hits) / len(retrieved) if retrieved else 0.0
        recall = len(hits) / len(relevant)
        rr = next((1 / i for i, c in enumerate(retrieved, 1) if c in relevant), 0.0)
        passed = not res.refused and recall > 0
    else:
        passed = res.refused
    return CaseResult(
        case["id"], case["category"], case["query"], retrieved, relevant,
        case["expect_refusal"], res.refused, precision, recall, rr, latency, passed,
    )  # fmt: skip


def _mean(xs: list[float]) -> float:
    return statistics.fmean(xs) if xs else 0.0


def summarise(results: list[CaseResult]) -> dict:
    answerable = [r for r in results if not r.expect_refusal]
    ood = [r for r in results if r.expect_refusal]
    lat = sorted(r.latency_ms for r in results)
    p95 = lat[min(len(lat) - 1, round(0.95 * (len(lat) - 1)))]
    summary = {
        "cases": len(results),
        "precision_at_5": _mean([r.precision for r in answerable]),
        "recall_at_5": _mean([r.recall for r in answerable]),
        "mrr": _mean([r.reciprocal_rank for r in answerable]),
        "false_refusal_rate": _mean([float(r.refused) for r in answerable]),
        "hallucination_rejection_rate": _mean([float(r.refused) for r in ood]),
        "latency_ms_p50": statistics.median(lat),
        "latency_ms_p95": p95,
        "pass_rate": _mean([float(r.passed) for r in results]),
        "by_category": {},
    }
    for cat in sorted({r.category for r in results}):
        rs = [r for r in results if r.category == cat]
        ans = [r for r in rs if not r.expect_refusal]
        summary["by_category"][cat] = {
            "cases": len(rs),
            "pass_rate": _mean([float(r.passed) for r in rs]),
            "recall_at_5": _mean([r.recall for r in ans]) if ans else None,
            "mrr": _mean([r.reciprocal_rank for r in ans]) if ans else None,
            "refusal_rate": _mean([float(r.refused) for r in rs]),
        }
    return summary


def run(dataset_path: Path = DEFAULT_DATASET, kb_path: Path = DEFAULT_KB) -> tuple[dict, list[CaseResult]]:
    dataset = json.loads(Path(dataset_path).read_text(encoding="utf-8"))
    engine = HybridSearchEngine(load_cards(kb_path))
    engine.search("warm-up")  # exclude first-call overhead from latency stats
    results = [evaluate_case(engine, c) for c in dataset["cases"]]
    return summarise(results), results


def _pct(x: float | None) -> str:
    return "—" if x is None else f"{x * 100:.1f}%"


def render_markdown(summary: dict, results: list[CaseResult], categories: dict[str, str]) -> str:
    out = [
        "# Benchmark Report",
        "",
        "Generated by `python -m evaluation.eval_runner --report evaluation/benchmark_report.md`.",
        "Default offline backends: `HashingEmbedder` (dense) + `BM25Okapi` (sparse) → RRF (k=60) → "
        "`LexicalCrossReranker`, Top-K ≤ 5.",
        "",
        "> **Scope note:** 30 hand-written cases over a 6-card knowledge base. The guardrail thresholds were "
        "tuned on this same set, so treat these numbers as a regression baseline, not a held-out estimate.",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Cases | {summary['cases']} |",
        f"| Precision@5 | {_pct(summary['precision_at_5'])} |",
        f"| Recall@5 | {_pct(summary['recall_at_5'])} |",
        f"| MRR | {summary['mrr']:.3f} |",
        f"| Hallucination rejection rate | {_pct(summary['hallucination_rejection_rate'])} |",
        f"| False refusal rate | {_pct(summary['false_refusal_rate'])} |",
        f"| Latency p50 / p95 | {summary['latency_ms_p50']:.2f} ms / {summary['latency_ms_p95']:.2f} ms |",
        f"| Overall pass rate | {_pct(summary['pass_rate'])} |",
        "",
        "## By category",
        "",
        "| Category | Cases | Pass rate | Recall@5 | MRR | Refusal rate |",
        "|---|---|---|---|---|---|",
    ]
    for cat, s in summary["by_category"].items():
        mrr = "—" if s["mrr"] is None else f"{s['mrr']:.3f}"
        out.append(
            f"| {cat} — {categories.get(cat, '')} | {s['cases']} | {_pct(s['pass_rate'])} | "
            f"{_pct(s['recall_at_5'])} | {mrr} | {_pct(s['refusal_rate'])} |"
        )
    out += [
        "",
        "## Per-case results",
        "",
        "| ID | Query | Expected | Retrieved | Refused | Pass |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        expected = "refuse" if r.expect_refusal else ", ".join(r.relevant)
        out.append(
            f"| {r.id} | {r.query} | {expected} | {', '.join(r.retrieved) or '—'} | "
            f"{'yes' if r.refused else 'no'} | {'✅' if r.passed else '❌'} |"
        )
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    p.add_argument("--kb", type=Path, default=DEFAULT_KB)
    p.add_argument("--report", type=Path, help="write a markdown report to this path")
    p.add_argument("--json", type=Path, help="write raw results as JSON")
    p.add_argument("--min-recall", type=float, default=None, help="fail if Recall@5 is below this")
    p.add_argument("--min-rejection", type=float, default=None, help="fail if rejection rate is below this")
    p.add_argument("--max-false-refusal", type=float, default=None, help="fail if false refusals exceed this")
    args = p.parse_args(argv)

    summary, results = run(args.dataset, args.kb)
    categories = json.loads(args.dataset.read_text(encoding="utf-8")).get("categories", {})
    for r in results:
        print(f"{'PASS' if r.passed else 'FAIL'} {r.id} refused={r.refused!s:5} top={r.retrieved[:3]}  {r.query}")
    print(json.dumps({k: v for k, v in summary.items() if k != "by_category"}, indent=2))

    if args.report:
        args.report.write_text(render_markdown(summary, results, categories), encoding="utf-8")
    if args.json:
        args.json.write_text(json.dumps({"summary": summary, "results": [asdict(r) for r in results]}, indent=2))

    failures = []
    if args.min_recall is not None and summary["recall_at_5"] < args.min_recall:
        failures.append(f"Recall@5 {summary['recall_at_5']:.3f} < {args.min_recall}")
    if args.min_rejection is not None and summary["hallucination_rejection_rate"] < args.min_rejection:
        failures.append(f"rejection {summary['hallucination_rejection_rate']:.3f} < {args.min_rejection}")
    if args.max_false_refusal is not None and summary["false_refusal_rate"] > args.max_false_refusal:
        failures.append(f"false refusal {summary['false_refusal_rate']:.3f} > {args.max_false_refusal}")
    for f in failures:
        print(f"BENCHMARK GATE FAILED: {f}", file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
